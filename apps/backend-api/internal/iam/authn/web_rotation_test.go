// A rotation replaces the key that seals; it does not reissue what the previous
// key already sealed or derived. Stored TOTP secrets, unused recovery codes,
// invitations already in someone's inbox and password-recovery links still in
// flight all outlive the key that produced them, and none of them can be
// regenerated by the deployment on the user's behalf. These tests hold the ring
// to that: everything the retired key produced stays recognized while the key
// is still listed, and stops the moment it is taken out.

const rotationTestPlaintextSecret = "not-a-real-totp-secret"

func retiredAuthnKey() []byte { return []byte(strings.Repeat("k", 32)) }

func replacementAuthnKey() []byte { return []byte("fedcba9876543210fedcba9876543210") }

// oldMFAPurposeKey reproduces the subkey derivation this module used before the
// key ring existed. It is duplicated here on purpose: if the derivation ever
// changes, that has to surface as a failing test rather than as a deployment
// where every stored secret and every issued token has quietly stopped being
// recognized.
func oldMFAPurposeKey(key []byte, purpose string) []byte {
	mac := hmac.New(sha256.New, key)
	_, _ = mac.Write([]byte("platform:mfa:key:" + purpose))
	return mac.Sum(nil)
}

func sealAuthnDataTheWayTheOldCodeDid(
	t *testing.T, key []byte, purpose, associatedData string, plain []byte,
) string {
	t.Helper()
	block, err := aes.NewCipher(oldMFAPurposeKey(key, "encryption:"+purpose))
	require.NoError(t, err)
	gcm, err := cipher.NewGCM(block)
	require.NoError(t, err)
	nonce := make([]byte, gcm.NonceSize())
	_, err = rand.Read(nonce)
	require.NoError(t, err)
	sealed := gcm.Seal(nonce, nonce, plain, []byte(associatedData))
	return "v1." + base64.RawURLEncoding.EncodeToString(sealed)
}

func macTheWayTheOldCodeDid(key []byte, purpose string, message []byte) string {
	mac := hmac.New(sha256.New, oldMFAPurposeKey(key, purpose))
	_, _ = mac.Write(message)
	return hex.EncodeToString(mac.Sum(nil))
}

// TestAuthnResolvesTheKeysARotationLeavesBehind covers the configuration a
// deployment sits in for as long as a rotation takes: one key sealing, one or
// more still opening what they sealed earlier.
func TestAuthnResolvesTheKeysARotationLeavesBehind(t *testing.T) {
	active := base64.RawStdEncoding.EncodeToString(replacementAuthnKey())
	retired := base64.RawStdEncoding.EncodeToString(retiredAuthnKey())

	retiredFile := filepath.Join(t.TempDir(), "authn.previous.key")
	require.NoError(t, os.WriteFile(retiredFile, []byte(retired+"\n"), 0o600))

	keys, err := resolveMFAKeyring(authnext.MFAConfig{
		EncryptionKey:              active,
		PreviousEncryptionKeyFiles: []string{retiredFile},
	})
	require.NoError(t, err)
	assert.Equal(t, newMFATestKeyring(t, replacementAuthnKey(), retiredAuthnKey()).IDs(), keys.IDs())

	// Browser authentication cannot run without a key, so retired keys on their
	// own are a startup failure rather than a rotation that half happened.
	_, err = resolveMFAKeyring(authnext.MFAConfig{PreviousEncryptionKeys: []string{retired}})
	require.Error(t, err)
	assert.Contains(t, err.Error(), "required")

	// Naming one key twice is how an operator convinces themselves they have
	// rotated when they have not, so it is refused rather than deduplicated.
	_, err = resolveMFAKeyring(authnext.MFAConfig{
		EncryptionKey:          active,
		PreviousEncryptionKeys: []string{active},
	})
	require.Error(t, err)
	assert.Contains(t, err.Error(), "authn MFA encryption key")

	_, err = resolveMFAKeyring(authnext.MFAConfig{
		EncryptionKey:              active,
		PreviousEncryptionKeys:     []string{retired},
		PreviousEncryptionKeyFiles: []string{retiredFile},
	})
	require.Error(t, err)
}

// TestAuthnRecognizesWhatWasWrittenBeforeTheKeyRing is the compatibility this
// change is only safe because of. Every value below is written the way the
// previous build wrote it, and read back through the ring unchanged.
func TestAuthnRecognizesWhatWasWrittenBeforeTheKeyRing(t *testing.T) {
	service, _ := newLocalService(t)
	key := retiredAuthnKey()
	const principal = guid.ID(101)

	secret := sealAuthnDataTheWayTheOldCodeDid(
		t, key, "v1", principal.String(), []byte(rotationTestPlaintextSecret),
	)
	opened, err := service.decryptMFASecret(principal, secret)
	require.NoError(t, err)
	assert.Equal(t, rotationTestPlaintextSecret, opened)

	code := normalizeRecoveryCode("abcd-efgh")
	assert.Equal(t,
		macTheWayTheOldCodeDid(key, "recovery:v1", recoveryCodeMessage(code)),
		service.recoveryCodeHash(code),
	)

	recoveryToken := "rec1_not-a-real-recovery-token"
	assert.Equal(t,
		macTheWayTheOldCodeDid(key, "password-recovery:v1", passwordRecoveryMessage(recoveryToken)),
		service.passwordRecoveryHMAC(recoveryToken),
	)

	verificationToken := "ver1_not-a-real-verification-token"
	assert.Equal(t,
		macTheWayTheOldCodeDid(key, "email-verification:v1", emailVerificationMessage(verificationToken)),
		service.emailVerificationHMAC(verificationToken),
	)

	invitationToken, digest, err := service.IssueInvitationToken(42)
	require.NoError(t, err)
	message, err := invitationTokenMessage(service, invitationToken)
	require.NoError(t, err)
	assert.Equal(t, macTheWayTheOldCodeDid(key, "invitation:v1", message), digest)
}

// TestAuthnRecognizesWhatARetiredKeySealed walks a full rotation across all five
// things this key protects. Recovery codes are the case that decides the shape
// of the API: they are looked up by their stored value, so acceptance has to ask
// every key rather than recompute one digest.
func TestAuthnRecognizesWhatARetiredKeySealed(t *testing.T) {
	service, _ := newLocalService(t)
	const principal = guid.ID(101)

	// Everything below is produced while the retired key is still the active one.
	secret, err := service.encryptMFASecret(principal, rotationTestPlaintextSecret)
	require.NoError(t, err)
	code := normalizeRecoveryCode("abcd-efgh")
	storedCode := service.recoveryCodeHash(code)
	recoveryToken := "rec1_not-a-real-recovery-token"
	storedRecovery := service.passwordRecoveryHMAC(recoveryToken)
	verificationToken := "ver1_not-a-real-verification-token"
	storedVerification := service.emailVerificationHMAC(verificationToken)
	invitationToken, invitationDigest, err := service.IssueInvitationToken(42)
	require.NoError(t, err)

	service.mfaKeys = newMFATestKeyring(t, replacementAuthnKey(), retiredAuthnKey())

	opened, err := service.decryptMFASecret(principal, secret)
	require.NoError(t, err)
	assert.Equal(t, rotationTestPlaintextSecret, opened)
	assert.Contains(t, service.recoveryCodeHashes(code), storedCode)
	assert.Contains(t, service.passwordRecoveryHMACs(recoveryToken), storedRecovery)
	assert.True(t, service.passwordRecoveryMatches(recoveryToken, storedRecovery))
	assert.Contains(t, service.emailVerificationHMACs(verificationToken), storedVerification)
	assert.True(t, service.emailVerificationMatches(verificationToken, storedVerification))
	assert.True(t, service.InvitationTokenMatches(invitationToken, invitationDigest))

	// What the ring writes now records the active key, so rewrapping a stored
	// secret is a read and a write rather than a migration somebody hand-writes.
	assert.True(t, service.mfaKeys.NeedsRewrap(secret))
	resealed, err := service.encryptMFASecret(principal, opened)
	require.NoError(t, err)
	assert.False(t, service.mfaKeys.NeedsRewrap(resealed))

	// Taking the retired key out is what finishes the rotation, and it is only
	// safe once nothing it produced is still outstanding.
	service.mfaKeys = newMFATestKeyring(t, replacementAuthnKey())
	_, err = service.decryptMFASecret(principal, secret)
	assert.ErrorIs(t, err, errRetiredAuthnKey)
	assert.NotContains(t, service.recoveryCodeHashes(code), storedCode)
	assert.False(t, service.passwordRecoveryMatches(recoveryToken, storedRecovery))
	assert.False(t, service.emailVerificationMatches(verificationToken, storedVerification))
	assert.False(t, service.InvitationTokenMatches(invitationToken, invitationDigest))
}
