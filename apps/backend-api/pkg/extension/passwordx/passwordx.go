// Package passwordx hashes and verifies passwords using bounded Argon2id parameters.
package passwordx

import (
	"crypto/rand"
	"crypto/subtle"
	"encoding/base64"
	"errors"
	"fmt"
	"io"
	"strings"

	"golang.org/x/crypto/argon2"
)

const (
	memory        = 19 * 1024
	iterations    = 2
	parallelism   = 1
	saltLength    = 16
	keyLength     = 32
	encodedPrefix = "$argon2id$v=19$m=19456,t=2,p=1$"
)

var ErrInvalidHash = errors.New("invalid password hash")

var encodedHashLength = len(encodedPrefix) +
	base64.RawStdEncoding.EncodedLen(saltLength) + 1 +
	base64.RawStdEncoding.EncodedLen(keyLength)

func Hash(password string) (string, error) {
	return hash(password, rand.Reader)
}

func hash(password string, random io.Reader) (string, error) {
	if password == "" {
		return "", errors.New("password is empty")
	}
	salt := make([]byte, saltLength)
	if _, err := io.ReadFull(random, salt); err != nil {
		return "", fmt.Errorf("generate password salt: %w", err)
	}
	digest := argon2.IDKey([]byte(password), salt, iterations, memory, parallelism, keyLength)
	return fmt.Sprintf("$argon2id$v=19$m=%d,t=%d,p=%d$%s$%s", memory, iterations, parallelism,
		base64.RawStdEncoding.EncodeToString(salt), base64.RawStdEncoding.EncodeToString(digest)), nil
}

func Verify(encoded, password string) (bool, error) {
	// Every hash generated by this service has one exact parameter set and
	// encoded length. Reject oversized database values before any tokenization
	// can allocate in proportion to untrusted delimiter counts.
	if len(encoded) != encodedHashLength || !strings.HasPrefix(encoded, encodedPrefix) {
		return false, ErrInvalidHash
	}
	saltText, digestText, ok := strings.Cut(encoded[len(encodedPrefix):], "$")
	if !ok {
		return false, ErrInvalidHash
	}
	if len(saltText) != base64.RawStdEncoding.EncodedLen(saltLength) ||
		len(digestText) != base64.RawStdEncoding.EncodedLen(keyLength) {
		return false, ErrInvalidHash
	}
	salt, err := base64.RawStdEncoding.DecodeString(saltText)
	if err != nil || len(salt) != saltLength {
		return false, ErrInvalidHash
	}
	want, err := base64.RawStdEncoding.DecodeString(digestText)
	if err != nil || len(want) != keyLength {
		return false, ErrInvalidHash
	}
	got := argon2.IDKey([]byte(password), salt, iterations, memory, parallelism, keyLength)
	return subtle.ConstantTimeCompare(got, want) == 1, nil
}
