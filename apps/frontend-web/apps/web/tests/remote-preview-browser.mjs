import assert from "node:assert/strict"
import { chromium } from "playwright"

const baseURL = process.env.PREVIEW_FIXTURE_URL
assert(baseURL && ["localhost", "127.0.0.1"].includes(new URL(baseURL).hostname), "An isolated local Vite URL is required")
const browser = await chromium.launch({channel: "chrome", headless: true})
try {
  const context = await browser.newContext({viewport: {width: 1280, height: 800}})
  await context.route("https://*.preview.example.test/**", (route) => route.fulfill({contentType: "text/html", body: "<p>Isolated gateway fixture</p>"}))
  const page = await context.newPage()
  const errors = []
  page.on("pageerror", (error) => errors.push(error.message))
  const at = (query = "") => page.goto(`${baseURL}/tests/fixtures/remote-preview.html${query}`)
  await at("?disabled&path")
  await page.getByRole("button", {name: "Enable previews", exact: true}).click()
  await page.getByRole("button", {name: "Disable previews", exact: true}).waitFor()
  const policy = await page.evaluate(() => window.fixtureWrites[0])
  assert.deepEqual(policy, {path: "/machines/11/remote-access", body: {allow_remote_terminal: false, allow_remote_preview: true}})
  await page.getByRole("spinbutton", {name: "Port", exact: true}).fill("8080")
  await page.getByRole("button", {name: "Create preview", exact: true}).click()
  await page.getByText("Path mode:", {exact: false}).waitFor()
  const popupPromise = context.waitForEvent("page")
  await page.getByRole("button", {name: "Open preview", exact: true}).click()
  const popup = await popupPromise
  await popup.waitForURL("https://*.preview.example.test/**")
  assert.equal(await popup.evaluate(() => window.opener), null)
  assert.equal(await page.locator("iframe").count(), 0)
  await popup.close()
  await page.getByRole("button", {name: "Stop preview", exact: true}).click()
  await page.getByText("Port: 8080 · Stopped", {exact: true}).waitFor()
  assert.equal(await page.getByRole("button", {name: "Open preview", exact: true}).count(), 0)
  await page.getByRole("combobox", {name: "Execution ID", exact: true}).selectOption("22")
  await page.getByText("No previews for this execution.", {exact: true}).waitFor()
  await at("?readonly")
  await page.getByRole("heading", {name: "Service preview", exact: true}).waitFor()
  assert.equal(await page.getByRole("button", {name: "Create preview", exact: true}).count(), 0)
  assert.equal(await page.getByRole("button", {name: "Disable previews", exact: true}).count(), 0)
  await at("?readonly&seeded")
  await page.getByRole("button", {name: "Stop preview", exact: true}).waitFor()
  await at("?readonly&seeded&other")
  await page.getByRole("button", {name: "Open preview", exact: true}).waitFor()
  assert.equal(await page.getByRole("button", {name: "Stop preview", exact: true}).count(), 0)
  await at("?offline")
  await page.getByRole("spinbutton", {name: "Port", exact: true}).fill("8080")
  assert(await page.getByRole("button", {name: "Create preview", exact: true}).isDisabled())
  await at("?exchange&denied")
  await page.getByRole("alert").filter({hasText: "Fixture preview access denied"}).waitFor()
  await at("?exchange&unsafe")
  await page.getByRole("alert").filter({hasText: "invalid_response"}).waitFor()
  assert(!page.url().includes("app-bytes"))
  await at("?exchange&invalid")
  await page.getByRole("alert").filter({hasText: "This preview link is invalid"}).waitFor()
  assert.equal((await page.evaluate(() => window.fixtureWrites)).length, 0)
  await at("?exchange&anonymous")
  await page.getByRole("status").filter({hasText: "Fixture login: /preview-access?label="}).waitFor()
  assert.equal((await page.evaluate(() => window.fixtureWrites)).length, 0)
  await at("?terminal&terminal-retry")
  await page.getByRole("button", {name: "Connect", exact: true}).click()
  const dialog = page.getByRole("dialog")
  await dialog.getByLabel("Current password", {exact: true}).fill("fixture-password")
  await dialog.getByRole("button", {name: "Continue", exact: true}).click()
  await dialog.getByRole("alert").filter({hasText: "Fixture uncertain create"}).waitFor()
  await dialog.getByRole("button", {name: "Continue", exact: true}).click()
  await dialog.waitFor({state: "hidden"})
  await page.getByRole("status").filter({hasText: "OPENING"}).waitFor()
  assert(await page.getByRole("textbox", {name: "Command", exact: true}).isDisabled())
  const attempts = await page.evaluate(() => window.fixtureWrites.filter((row) => row.path.endsWith("/terminal-sessions")))
  assert.equal(attempts.length, 2)
  assert.match(attempts[0].key, /^[\x21-\x7e]{1,64}$/)
  assert.equal(attempts[0].key, attempts[1].key)
  assert.notEqual(attempts[0].body.reauth_proof, attempts[1].body.reauth_proof)
  assert.equal((await page.evaluate(() => window.fixtureRequests.filter((path) => path.endsWith("/41/stream")))).length, 0)
  await page.evaluate(() => window.fixtureOpenTerminal())
  await page.getByRole("textbox", {name: "Command", exact: true}).waitFor()
  await page.waitForFunction(() => !document.querySelector('input[autocomplete="off"]')?.disabled)
  await page.getByRole("textbox", {name: "Command", exact: true}).fill("pwd")
  await page.getByRole("button", {name: "Send", exact: true}).click()
  await page.getByRole("button", {name: "Revoke session", exact: true}).click()
  await page.getByRole("status").filter({hasText: "CLOSED"}).waitFor()
  await page.getByRole("button", {name: "Connect", exact: true}).click()
  await dialog.getByLabel("Current password", {exact: true}).fill("fixture-password")
  await dialog.getByRole("button", {name: "Continue", exact: true}).click()
  await dialog.waitFor({state: "hidden"})
  const keys = await page.evaluate(() => window.fixtureWrites.filter((row) => row.path.endsWith("/terminal-sessions")).map((row) => row.key))
  assert.notEqual(keys[2], keys[1], "a new session after closure receives a new intent key")
  for (const [locale, title] of [["zh-CN", "服务预览"], ["ms-MY", "Pratonton perkhidmatan"]]) {
    await page.setViewportSize({width: 375, height: 812})
    await at(`?locale=${locale}&seeded`)
    await page.getByRole("heading", {name: title, exact: true}).waitFor()
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))
  }
  await at("?exchange")
  await page.waitForURL("https://*.preview.example.test/**")
  assert.deepEqual(errors, [])
  console.log("PASS: preview policy/create/open/stop, path warning, execution isolation, permission/offline gates, auth exchange success/denial/unsafe/invalid/anonymous")
} finally {await browser.close()}
