// Regenerates src/lib/api-schema.ts from the backend's OpenAPI document.
//
// The document itself is the backend's to publish. Until it is committed there,
// pass a running instance instead:
//
//   bun scripts/generate-api-types.mjs --spec http://localhost:8091/api/openapi.json
//
// Generating from a running instance is fine for a person at a keyboard and no
// good for CI, which is why the default is a path on disk.
//
// With --check nothing is written: the types the document would produce are
// compared against the committed ones. A client whose types have drifted from
// the document compiles against a contract the server stopped serving, and the
// compiler cannot say so, because the types it checks are the stale ones.

import { spawnSync } from "node:child_process"
import {
  existsSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { fileURLToPath } from "node:url"

const repoRoot = fileURLToPath(new URL("../../../../../", import.meta.url))
const defaultSpec = join(repoRoot, "apps/backend-api/docs/openapi.json")
const output = fileURLToPath(new URL("../src/lib/api-schema.ts", import.meta.url))
// Types vanish at runtime, and the client has to know at runtime whether a
// resource is addressed under its tenant or globally. Guessing that is what
// let fifty-eight call sites keep sending a tenant prefix to routes that had
// moved, each answering 404 the moment a tenant was selected.
const routesOutput = fileURLToPath(
  new URL("../src/lib/api-routes.ts", import.meta.url)
)

function routesModule(specification) {
  const paths = Object.keys(JSON.parse(specification).paths).sort()
  return [
    "// This file was generated by scripts/generate-api-types.mjs.",
    "// Do not make direct changes to the file.",
    "",
    "export const publishedRoutes: readonly string[] = [",
    ...paths.map((path) => `  ${JSON.stringify(path)},`),
    "]",
    "",
  ].join("\n")
}

const checking = process.argv.includes("--check")
const flag = process.argv.indexOf("--spec")
const spec = flag === -1 ? defaultSpec : process.argv[flag + 1]
if (!spec) throw new Error("--spec needs a path or a URL")

let input = spec
let scratch

if (/^https?:\/\//.test(spec)) {
  const response = await fetch(spec)
  if (!response.ok)
    throw new Error(`${spec} answered ${response.status}`)
  scratch = mkdtempSync(join(tmpdir(), "iam-openapi-"))
  input = join(scratch, "openapi.json")
  writeFileSync(input, await response.text())
} else if (!existsSync(input)) {
  throw new Error(
    `${input} does not exist. The backend publishes this document; until it does, ` +
      `point --spec at a running instance.`
  )
}

let compare
try {
  const target = checking
    ? join(
        (compare = mkdtempSync(join(tmpdir(), "iam-types-"))),
        "api-schema.ts"
      )
    : output
  const result = spawnSync(
    "bun",
    ["x", "openapi-typescript", input, "-o", target],
    { stdio: "inherit", shell: process.platform === "win32" }
  )
  if (result.status !== 0) process.exit(result.status ?? 1)
  const routes = routesModule(readFileSync(input, "utf8"))
  if (!checking) writeFileSync(routesOutput, routes)
  if (
    checking &&
    (!existsSync(routesOutput) ||
      readFileSync(routesOutput, "utf8") !== routes)
  ) {
    console.error(
      "src/lib/api-routes.ts no longer matches apps/backend-api/docs/openapi.json."
    )
    console.error("Run `bun run generate:api-types` and commit the result.")
    process.exit(1)
  }
  if (
    checking &&
    (!existsSync(output) ||
      readFileSync(output, "utf8") !== readFileSync(target, "utf8"))
  ) {
    console.error(
      "src/lib/api-schema.ts no longer matches apps/backend-api/docs/openapi.json."
    )
    console.error("Run `bun run generate:api-types` and commit the result.")
    process.exit(1)
  }
} finally {
  if (scratch) rmSync(scratch, { recursive: true, force: true })
  if (compare) rmSync(compare, { recursive: true, force: true })
}
