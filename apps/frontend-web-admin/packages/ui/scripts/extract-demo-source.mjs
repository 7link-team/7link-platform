// 读取 src/components/demos/*.tsx 的真实源码，生成 sources.generated.ts。
// 让组件展示页「代码」Tab 显示的源码 = 文件原文，永不与实现脱节。
// 接入 package.json 的 predev/prebuild，幂等。
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const demosDir = join(here, "..", "src", "components", "demos")
const outFile = join(demosDir, "sources.generated.ts")

const IGNORE = new Set(["index.tsx", "index.ts", "sources.generated.ts"])

const files = readdirSync(demosDir)
  // demo 文件 = 直接 .tsx；下划线前缀(_section/_code-block 等)为内部件，跳过
  .filter((f) => f.endsWith(".tsx") && !f.startsWith("_") && !IGNORE.has(f))
  .sort()

const entries = {}
for (const file of files) {
  const id = file.replace(/\.tsx$/, "")
  const text = readFileSync(join(demosDir, file), "utf8")
  // 展示用源码统一成 LF，避免把某台机器 checkout 的 CRLF 烘进产物。
  const raw = text.replace(/\r\n/g, "\n").replace(/\s+$/, "") + "\n"
  entries[id] = raw
}

const body = Object.entries(entries)
  .map(([id, src]) => `  ${JSON.stringify(id)}: ${JSON.stringify(src)},`)
  .join("\n")

const out = `// AUTO-GENERATED by scripts/extract-demo-source.mjs — do not edit by hand.
// Run \`bun run extract-demo-source\` (or it runs automatically on predev/prebuild).
export const demoSources: Record<string, string> = {
${body}
}
`

writeFileSync(outFile, out, "utf8")
console.log(`[extract-demo-source] wrote ${files.length} sources -> ${outFile}`)
